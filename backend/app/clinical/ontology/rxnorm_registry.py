@dataclass
class RenalDoseAdjustment:
    egfr_cutoff_moderate: float  # e.g., 30-59
    moderate_recommendation: str
    egfr_cutoff_severe: float    # e.g., 15-29
    severe_recommendation: str
    dialysis_recommendation: str
    is_dialyzable: bool

@dataclass
class RxNormEntry:
    rxcui: str
    generic_name: str
    brand_names: List[str]
    drug_class: DrugClass
    atc_code: str
    mechanism_of_action: str
    bioavailability_percent: float
    half_life_hours: float
    protein_binding_percent: float
    primary_elimination: str  # Renal, Hepatic, Biliary, Mixed
    standard_starting_dose: str
    maximum_daily_dose: str
    renal_adjustment: RenalDoseAdjustment
    hepatic_adjustment: str
    pregnancy_category: str
    black_box_warning: Optional[str] = None
    common_adverse_effects: List[str] = field(default_factory=list)
    cyp_metabolism: List[str] = field(default_factory=list)

class RxNormRegistry:
    _REGISTRY: Dict[str, RxNormEntry] = {}

    @classmethod
    def register(cls, entry: RxNormEntry) -> None:
        cls._REGISTRY[entry.rxcui] = entry

    @classmethod
    def get(cls, rxcui: str) -> Optional[RxNormEntry]:
        return cls._REGISTRY.get(rxcui.strip())

    @classmethod
    def get_by_name(cls, name: str) -> Optional[RxNormEntry]:
        q = name.lower().strip()
        for e in cls._REGISTRY.values():
            if e.generic_name.lower() == q or any(b.lower() == q for b in e.brand_names):
                return e
        return None

    @classmethod
    def search(cls, query: str) -> List[RxNormEntry]:
        q = query.lower().strip()
        return [e for e in cls._REGISTRY.values() if q in e.generic_name.lower() or any(q in b.lower() for b in e.brand_names)]

    @classmethod
    def get_renal_guidance(cls, rxcui: str, egfr: float) -> str:
        entry = cls.get(rxcui)
        if not entry:
            return "Drug not found in registry."
        adj = entry.renal_adjustment
        if egfr >= 60:
            return "Normal dosing; no dosage adjustment necessary for renal function."
        elif egfr >= adj.egfr_cutoff_moderate:
            return f"Moderate renal impairment: {adj.moderate_recommendation}"
        elif egfr >= adj.egfr_cutoff_severe:
            return f"Severe renal impairment: {adj.severe_recommendation}"
        else:
            return f"End-stage renal disease / Dialysis: {adj.dialysis_recommendation}"

