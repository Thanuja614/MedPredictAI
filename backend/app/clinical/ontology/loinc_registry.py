@dataclass
class ReferenceRange:
    low: float
    high: float
    unit: str
    panic_low: Optional[float] = None
    panic_high: Optional[float] = None

@dataclass
class LOINCEntry:
    loinc_num: str
    component: str
    short_name: str
    category: LabCategory
    specimen: SpecimenType
    conventional_unit: str
    si_unit: str
    si_conversion_factor: float  # Value in Conv * factor = Value in SI
    adult_male_range: ReferenceRange
    adult_female_range: ReferenceRange
    pediatric_range: ReferenceRange
    geriatric_range: ReferenceRange
    clinical_significance: str
    elevated_interpretation: str
    decreased_interpretation: str
    associated_icd10: List[str] = field(default_factory=list)

class LOINCRegistry:
    _REGISTRY: Dict[str, LOINCEntry] = {}

    @classmethod
    def register(cls, entry: LOINCEntry) -> None:
        cls._REGISTRY[entry.loinc_num] = entry

    @classmethod
    def get(cls, loinc_num: str) -> Optional[LOINCEntry]:
        return cls._REGISTRY.get(loinc_num.strip())

    @classmethod
    def all_codes(cls) -> List[str]:
        return sorted(list(cls._REGISTRY.keys()))

    @classmethod
    def filter_by_category(cls, category: LabCategory) -> List[LOINCEntry]:
        return [e for e in cls._REGISTRY.values() if e.category == category]

    @classmethod
    def search(cls, query: str) -> List[LOINCEntry]:
        q = query.lower().strip()
        return [e for e in cls._REGISTRY.values() if q in e.loinc_num.lower() or q in e.component.lower() or q in e.short_name.lower()]

    @classmethod
    def evaluate_biomarker(cls, loinc_num: str, value: float, unit: str, gender: str = "male", age: int = 45) -> Dict[str, Any]:
        entry = cls.get(loinc_num)
        if not entry:
            return {"error": f"LOINC code {loinc_num} not found", "status": "UNKNOWN"}
        # Normalize unit if in SI
        norm_val = value
        if unit.lower() == entry.si_unit.lower() and entry.conventional_unit.lower() != entry.si_unit.lower():
            norm_val = value / entry.si_conversion_factor

        ref = entry.adult_male_range if gender.lower() == "male" else entry.adult_female_range
        if age < 18:
            ref = entry.pediatric_range
        elif age >= 65:
            ref = entry.geriatric_range

        status = "NORMAL"
        is_panic = False
        interp = "Value within reference interval"
        if ref.panic_low is not None and norm_val < ref.panic_low:
            status = "CRITICAL_LOW"
            is_panic = True
            interp = f"CRITICAL PANIC LOW: {entry.decreased_interpretation}"
        elif ref.panic_high is not None and norm_val > ref.panic_high:
            status = "CRITICAL_HIGH"
            is_panic = True
            interp = f"CRITICAL PANIC HIGH: {entry.elevated_interpretation}"
        elif norm_val < ref.low:
            status = "LOW"
            interp = entry.decreased_interpretation
        elif norm_val > ref.high:
            status = "HIGH"
            interp = entry.elevated_interpretation

        return {
            "loinc_num": entry.loinc_num,
            "component": entry.component,
            "short_name": entry.short_name,
            "value": value,
            "normalized_value": round(norm_val, 2),
            "reference_interval": f"{ref.low} - {ref.high} {ref.unit}",
            "status": status,
            "is_critical_panic": is_panic,
            "interpretation": interp,
            "associated_conditions": entry.associated_icd10
        }

