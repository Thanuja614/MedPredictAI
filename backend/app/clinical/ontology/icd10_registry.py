class SeverityLevel(str, Enum):
    MILD = "Mild"
    MODERATE = "Moderate"
    SEVERE = "Severe"
    LIFE_THREATENING = "Life Threatening"

@dataclass
class ICD10Entry:
    code: str
    title: str
    category: DiseaseCategory
    chapter: str
    is_chronic: bool
    severity: SeverityLevel
    charlson_weight: int
    elixhauser_weight: int
    hcc_category: Optional[str]
    typical_symptoms: List[str]
    diagnostic_criteria: List[str]
    primary_lab_tests: List[str]
    first_line_medications: List[str]
    risk_factors: List[str]
    synonyms: List[str] = field(default_factory=list)
    complications: List[str] = field(default_factory=list)

class ICD10Registry:
    _REGISTRY: Dict[str, ICD10Entry] = {}

    @classmethod
    def register(cls, entry: ICD10Entry) -> None:
        cls._REGISTRY[entry.code] = entry

    @classmethod
    def get(cls, code: str) -> Optional[ICD10Entry]:
        return cls._REGISTRY.get(code.upper().strip())

    @classmethod
    def all_codes(cls) -> List[str]:
        return sorted(list(cls._REGISTRY.keys()))

    @classmethod
    def filter_by_category(cls, category: DiseaseCategory) -> List[ICD10Entry]:
        return [e for e in cls._REGISTRY.values() if e.category == category]

    @classmethod
    def filter_chronic(cls) -> List[ICD10Entry]:
        return [e for e in cls._REGISTRY.values() if e.is_chronic]

    @classmethod
    def search(cls, query: str) -> List[ICD10Entry]:
        q = query.lower().strip()
        results = []
        for e in cls._REGISTRY.values():
            if q in e.code.lower() or q in e.title.lower():
                results.append(e)
            elif any(q in s.lower() for s in e.typical_symptoms):
                results.append(e)
            elif any(q in syn.lower() for syn in e.synonyms):
                results.append(e)
        return results

    @classmethod
    def calculate_charlson_score(cls, codes: List[str]) -> Dict[str, Any]:
        total_score = 0
        matched_conditions = []
        for code in codes:
            entry = cls.get(code)
            if entry and entry.charlson_weight > 0:
                total_score += entry.charlson_weight
                matched_conditions.append({
                    "code": entry.code,
                    "title": entry.title,
                    "weight": entry.charlson_weight
                })
        # Estimated 10-year survival probability based on Charlson index
        if total_score == 0:
            est_10yr_survival = 0.98
        elif total_score == 1:
            est_10yr_survival = 0.96
        elif total_score == 2:
            est_10yr_survival = 0.90
        elif total_score == 3:
            est_10yr_survival = 0.77
        elif total_score == 4:
            est_10yr_survival = 0.53
        elif total_score == 5:
            est_10yr_survival = 0.21
        else:
            est_10yr_survival = 0.05
        return {
            "charlson_comorbidity_index": total_score,
            "estimated_10yr_survival_probability": est_10yr_survival,
            "matched_conditions": matched_conditions
        }

    @classmethod
    def calculate_elixhauser_score(cls, codes: List[str]) -> Dict[str, Any]:
        total_score = 0
        matched = []
        for code in codes:
            entry = cls.get(code)
            if entry and entry.elixhauser_weight != 0:
                total_score += entry.elixhauser_weight
                matched.append({
                    "code": entry.code,
                    "title": entry.title,
                    "weight": entry.elixhauser_weight
                })
        in_hospital_mortality_risk = min(0.95, max(0.01, 0.02 + (total_score * 0.035)))
        return {
            "elixhauser_comorbidity_score": total_score,
            "estimated_in_hospital_mortality_risk": round(in_hospital_mortality_risk, 4),
            "matched_conditions": matched
        }

