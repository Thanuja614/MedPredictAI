"""
MedPredict AI — Main Application Entrypoint
FastAPI application with lifespan management, CORS, middleware, and OpenAPI documentation.
"""

import uuid
import time
from contextlib import asynccontextmanager
from fastapi import FastAPI, Request
from fastapi.middleware.cors import CORSMiddleware
from fastapi.exceptions import RequestValidationError
from starlette.exceptions import HTTPException as StarletteHTTPException

from backend.app.core.config import settings
from backend.app.core.logging import logger, correlation_id_ctx
from backend.app.core.errors import (
    MedPredictAPIException,
    app_exception_handler,
    http_exception_handler,
    validation_exception_handler,
    unhandled_exception_handler
)
from backend.app.core.database import engine, Base
import backend.app.models  # Registers all 27 ORM models with Base metadata
from backend.app.api.v1.api import api_router

@asynccontextmanager
async def lifespan(app: FastAPI):
    """Application startup and shutdown event lifecycle."""
    logger.info(f"Starting {settings.APP_NAME} v{settings.PROJECT_VERSION} in {settings.APP_ENV} mode...")
    
    # Auto-initialize database tables in dev/test environments
    if settings.APP_ENV in ("development", "testing") or settings.DATABASE_URL.startswith("sqlite"):
        logger.info("Initializing relational database schema...")
        Base.metadata.create_all(bind=engine)
        logger.info("Relational schema verified.")

    yield
    logger.info(f"Shutting down {settings.APP_NAME}...")

# Create FastAPI application
app = FastAPI(
    title="MedPredict AI API",
    description=(
        "### Intelligent Multi-Disease Prediction & Medical Data Analytics Platform\n\n"
        "**MEDICAL SAFETY DISCLAIMER**: This application is strictly an educational, "
        "research, and clinical decision-support tool. It DOES NOT provide medical diagnosis, "
        "prescription, or treatment recommendations. All risk categories are model estimates."
    ),
    version=settings.PROJECT_VERSION,
    docs_url="/docs",
    redoc_url="/redoc",
    openapi_url=f"{settings.API_V1_STR}/openapi.json",
    lifespan=lifespan
)

# Correlation ID Middleware
@app.middleware("http")
async def correlation_id_middleware(request: Request, call_next):
    corr_id = request.headers.get("X-Correlation-ID", str(uuid.uuid4()))
    correlation_id_ctx.set(corr_id)
    start_time = time.time()
    
    response = await call_next(request)
    
    duration = time.time() - start_time
    response.headers["X-Correlation-ID"] = corr_id
    response.headers["X-Process-Time"] = f"{duration:.4f}s"
    
    logger.info(
        f"{request.method} {request.url.path} - status:{response.status_code} - duration:{duration:.4f}s"
    )
    return response

# CORS Configuration
origins = settings.BACKEND_CORS_ORIGINS
if isinstance(origins, str):
    origins = [o.strip() for o in origins.split(",") if o.strip()]

app.add_middleware(
    CORSMiddleware,
    allow_origins=origins,
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# Exception Handlers
app.add_exception_handler(MedPredictAPIException, app_exception_handler)
app.add_exception_handler(StarletteHTTPException, http_exception_handler)
app.add_exception_handler(RequestValidationError, validation_exception_handler)
app.add_exception_handler(Exception, unhandled_exception_handler)

# Mount API Routers
app.include_router(api_router, prefix=settings.API_V1_STR)

@app.get("/", tags=["Root"])
def root():
    return {
        "app": settings.APP_NAME,
        "version": settings.PROJECT_VERSION,
        "environment": settings.APP_ENV,
        "docs_url": "/docs",
        "api_v1": settings.API_V1_STR,
        "disclaimer": (
            "MedPredict AI is an educational and research-oriented decision-support platform. "
            "Its predictions are generated by machine-learning models and are not medical diagnoses."
        )
    }
